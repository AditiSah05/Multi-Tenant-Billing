/**
 * GSTR-1 Compliance Report Data Generator (B2B, B2C Large, B2C Small, HSN Summary, Returns)
 */
export const getGstr1Report = async (tenantId, filters = {}) => {
  const { startDate, endDate } = filters;
  const tenant = await prisma.tenant.findUnique({ where: { id: tenantId } });

  const where = { tenantId, status: { notIn: ['CANCELLED'] } };
  if (startDate || endDate) {
    where.createdAt = {};
    if (startDate) where.createdAt.gte = new Date(startDate);
    if (endDate) {
      const end = new Date(endDate);
      if (typeof endDate === 'string' && !endDate.includes('T')) {
        end.setUTCHours(23, 59, 59, 999);
      }
      where.createdAt.lte = end;
    }
  }

  const bills = await prisma.bill.findMany({
    where,
    include: {
      customer: true,
      items: { include: { product: true } },
      returns: true
    },
    orderBy: { createdAt: 'desc' }
  });

  const tenantStateCode = tenant?.gstNumber && tenant.gstNumber.length >= 2 ? tenant.gstNumber.slice(0, 2) : '27';

  const b2bInvoices = [];
  const b2cLargeInvoices = [];
  const b2cSmallInvoices = [];
  const hsnMap = new Map();

  let totalTaxableValueAll = 0;
  let totalCgstAll = 0;
  let totalSgstAll = 0;
  let totalIgstAll = 0;
  let totalGrandTotalAll = 0;

  for (const b of bills) {
    const isB2B = Boolean(b.gstin || (b.customer && b.customer.gstin && b.customer.gstin.trim().length >= 15));
    const customerGstin = (b.gstin || b.customer?.gstin || '').trim().toUpperCase();
    const customerStateCode = (b.stateCode || b.customer?.stateCode || (customerGstin.length >= 2 ? customerGstin.slice(0, 2) : tenantStateCode)).trim();
    const isInterState = Boolean(b.igstAmount > 0 || (customerStateCode && customerStateCode !== tenantStateCode));

    totalTaxableValueAll += b.subtotal;
    totalCgstAll += b.cgstAmount;
    totalSgstAll += b.sgstAmount;
    totalIgstAll += b.igstAmount;
    totalGrandTotalAll += b.grandTotal;

    const rowObj = {
      invoiceNumber: b.invoiceNumber,
      invoiceDate: b.createdAt ? b.createdAt.toISOString().split('T')[0] : '',
      customerName: b.businessName || b.contactPerson || (b.customer ? b.customer.name : 'Walk-in Customer'),
      customerGstin: customerGstin || 'N/A',
      placeOfSupplyStateCode: customerStateCode,
      subtotal: b.subtotal,
      cgstAmount: b.cgstAmount,
      sgstAmount: b.sgstAmount,
      igstAmount: b.igstAmount,
      totalTaxAmount: b.totalTaxAmount,
      grandTotal: b.grandTotal
    };

    if (isB2B) {
      b2bInvoices.push(rowObj);
    } else if (isInterState && b.grandTotal > 250000) {
      b2cLargeInvoices.push(rowObj);
    } else {
      b2cSmallInvoices.push(rowObj);
    }

    // Accumulate HSN Table 12 Data
    for (const item of b.items) {
      const hsn = (item.product?.hsnCode || 'N/A').trim().toUpperCase();
      const desc = item.product?.name || 'Goods';
      const uqc = item.unit || item.product?.unit || 'Pcs';
      const qty = item.quantity - item.returnedQuantity;
      if (qty <= 0) continue;

      const taxable = Math.round((item.lineTotal - item.taxAmount) * 100) / 100;
      const itemCgst = isInterState ? 0 : item.taxAmount / 2;
      const itemSgst = isInterState ? 0 : item.taxAmount / 2;
      const itemIgst = isInterState ? item.taxAmount : 0;

      if (hsnMap.has(hsn)) {
        const hRec = hsnMap.get(hsn);
        hRec.totalQuantity += qty;
        hRec.totalValue += item.lineTotal;
        hRec.taxableValue += taxable;
        hRec.cgst += itemCgst;
        hRec.sgst += itemSgst;
        hRec.igst += itemIgst;
        hRec.totalTax += item.taxAmount;
      } else {
        hsnMap.set(hsn, {
          hsnCode: hsn,
          description: desc,
          uqc,
          totalQuantity: qty,
          totalValue: item.lineTotal,
          taxableValue: taxable,
          cgst: itemCgst,
          sgst: itemSgst,
          igst: itemIgst,
          totalTax: item.taxAmount
        });
      }
    }
  }

  const hsnSummaryTable = Array.from(hsnMap.values()).map(h => ({
    ...h,
    totalQuantity: Math.round(h.totalQuantity * 1000) / 1000,
    totalValue: Math.round(h.totalValue * 100) / 100,
    taxableValue: Math.round(h.taxableValue * 100) / 100,
    cgst: Math.round(h.cgst * 100) / 100,
    cgstAmount: Math.round(h.cgst * 100) / 100,
    sgst: Math.round(h.sgst * 100) / 100,
    sgstAmount: Math.round(h.sgst * 100) / 100,
    igst: Math.round(h.igst * 100) / 100,
    igstAmount: Math.round(h.igst * 100) / 100,
    totalTax: Math.round(h.totalTax * 100) / 100,
    totalTaxAmount: Math.round(h.totalTax * 100) / 100
  }));

  return {
    period: {
      startDate: startDate || 'All Time',
      endDate: endDate || 'Current Date'
    },
    summary: {
      totalInvoicesCount: bills.length,
      b2bInvoicesCount: b2bInvoices.length,
      b2cLargeCount: b2cLargeInvoices.length,
      b2cSmallCount: b2cSmallInvoices.length,
      totalTaxableValue: Math.round(totalTaxableValueAll * 100) / 100,
      totalCgst: Math.round(totalCgstAll * 100) / 100,
      totalSgst: Math.round(totalSgstAll * 100) / 100,
      totalIgst: Math.round(totalIgstAll * 100) / 100,
      totalOutputTaxCollected: Math.round((totalCgstAll + totalSgstAll + totalIgstAll) * 100) / 100,
      totalInvoiceAmount: Math.round(totalGrandTotalAll * 100) / 100
    },
    tables: {
      b2bInvoices,
      b2cLargeInvoices,
      b2cSmallInvoices,
      hsnSummaryTable
    }
  };
};

/**
 * GSTR-3B Summary Report (Outward Tax Liabilities vs Input Tax Credit / ITC & ITC Reversals)
 */
export const getGstr3bReport = async (tenantId, filters = {}) => {
  const { startDate, endDate } = filters;

  const whereSales = { tenantId, status: { notIn: ['CANCELLED'] } };
  const wherePurchases = { tenantId, purchaseStatus: { notIn: ['CANCELLED'] } };

  if (startDate || endDate) {
    const dFilter = {};
    if (startDate) dFilter.gte = new Date(startDate);
    if (endDate) {
      const end = new Date(endDate);
      if (typeof endDate === 'string' && !endDate.includes('T')) {
        end.setUTCHours(23, 59, 59, 999);
      }
      dFilter.lte = end;
    }
    whereSales.createdAt = dFilter;
    wherePurchases.invoiceDate = dFilter;
  }

  // 1. Table 3.1(a) Outward Taxable Supplies (Sales)
  const salesAgg = await prisma.bill.aggregate({
    where: whereSales,
    _sum: {
      subtotal: true,
      cgstAmount: true,
      sgstAmount: true,
      igstAmount: true,
      totalTaxAmount: true,
      grandTotal: true
    }
  });

  const outwardTaxableValue = salesAgg._sum.subtotal || 0;
  const outwardCgst = salesAgg._sum.cgstAmount || 0;
  const outwardSgst = salesAgg._sum.sgstAmount || 0;
  const outwardIgst = salesAgg._sum.igstAmount || 0;
  const totalOutwardTax = salesAgg._sum.totalTaxAmount || 0;

  // 2. Table 4(A) Eligible Input Tax Credit / ITC (Purchases)
  const purchasesAgg = await prisma.purchaseInvoice.aggregate({
    where: wherePurchases,
    _sum: {
      subtotal: true,
      cgstAmount: true,
      sgstAmount: true,
      igstAmount: true,
      taxAmount: true,
      totalAmount: true
    }
  });

  const itcTaxableValue = purchasesAgg._sum.subtotal || 0;
  const itcCgst = purchasesAgg._sum.cgstAmount || 0;
  const itcSgst = purchasesAgg._sum.sgstAmount || 0;
  const itcIgst = purchasesAgg._sum.igstAmount || 0;
  const totalItcAvailable = purchasesAgg._sum.taxAmount || 0;

  // 3. Table 4(B) ITC Reversed (Purchase Returns)
  const purchaseReturns = await prisma.purchaseReturn.findMany({
    where: { tenantId, ...(startDate || endDate ? { returnDate: wherePurchases.invoiceDate } : {}) }
  });

  let totalItcReversed = 0;
  for (const pr of purchaseReturns) {
    totalItcReversed += (pr.totalReturnAmount - pr.taxableReturnAmount) || 0;
  }

  const netEligibleItc = Math.max(0, totalItcAvailable - totalItcReversed);

  // 4. Net Tax Liability / Payable
  const netCgstPayable = Math.round(Math.max(0, outwardCgst - itcCgst) * 100) / 100;
  const netSgstPayable = Math.round(Math.max(0, outwardSgst - itcSgst) * 100) / 100;
  const netIgstPayable = Math.round(Math.max(0, outwardIgst - itcIgst) * 100) / 100;
  
  const rawNetPayable = Math.round((totalOutwardTax - netEligibleItc) * 100) / 100;
  const netTotalTaxPayable = Math.max(0, rawNetPayable);
  const excessItcCreditBalance = rawNetPayable < 0 ? Math.round(Math.abs(rawNetPayable) * 100) / 100 : 0;

  return {
    period: {
      startDate: startDate || 'All Time',
      endDate: endDate || 'Current Date'
    },
    table31_OutwardTaxableSupplies: {
      taxableValue: Math.round(outwardTaxableValue * 100) / 100,
      cgst: Math.round(outwardCgst * 100) / 100,
      sgst: Math.round(outwardSgst * 100) / 100,
      igst: Math.round(outwardIgst * 100) / 100,
      totalOutputTax: Math.round(totalOutwardTax * 100) / 100
    },
    table4_EligibleITC: {
      purchasesTaxableValue: Math.round(itcTaxableValue * 100) / 100,
      grossItcCgst: Math.round(itcCgst * 100) / 100,
      grossItcSgst: Math.round(itcSgst * 100) / 100,
      grossItcIgst: Math.round(itcIgst * 100) / 100,
      grossItcAvailable: Math.round(totalItcAvailable * 100) / 100,
      itcReversedOnReturns: Math.round(totalItcReversed * 100) / 100,
      netEligibleItc: Math.round(netEligibleItc * 100) / 100
    },
    netTaxPayableSummary: {
      netCgstPayable,
      netSgstPayable,
      netIgstPayable,
      netTaxPayableGovtDues: netTotalTaxPayable,
      netTotalTaxPayableGovtDues: netTotalTaxPayable,
      netTaxLiabilityGovtDues: netTotalTaxPayable,
      netTaxPayable: netTotalTaxPayable,
      totalNetTaxPayable: netTotalTaxPayable,
      excessItcCreditBalance,
      netTaxBalance: rawNetPayable
    }
  };
};

